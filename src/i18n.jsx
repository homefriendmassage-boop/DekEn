// Saved choice > phone/LINE language > Thai.
function detectLang() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved && dict[saved]) return saved
  } catch { /* storage blocked */ }
  for (const l of navigator.languages ?? [navigator.language]) {
    const code = String(l).toLowerCase().slice(0, 2)
    if (dict[code]) return code
  }
  return 'th'
}

const LOCALES = { th: 'th-TH', en: 'en-GB', zh: 'zh-CN' }
const I18nContext = createContext(null)

export function I18nProvider({ children, fixedLang }) {
  const [lang, setLangState] = useState(fixedLang ?? detectLang)

  const setLang = useCallback((l) => {
    setLangState(l)
    try { localStorage.setItem(STORAGE_KEY, l) } catch { /* ignore */ }
    document.documentElement.lang = l
  }, [])

  const value = useMemo(() => {
    const d = dict[lang]
    // t('key', { name }) -> replaces {name}
    const t = (key, vars = {}) =>
      String(d[key] ?? dict.en[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '')
    const money = (n) => `${Number(n).toLocaleString('en-US')} ${d.currency}`
    const catName = (c) => d.cat[c] ?? c   // unknown categories fall back to the raw value
    const statusName = (s) => d.st[s] ?? s
    const fmtDate = (v) => new Date(v).toLocaleDateString(LOCALES[lang], { day: 'numeric', month: 'short', year: 'numeric' })
    return { lang, setLang, t, money, catName, statusName, fmtDate }
  }, [lang, setLang])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export const useI18n = () => useContext(I18nContext)

export function LangSwitcher() {
  const { lang, setLang } = useI18n()
  return (
    <div className="flex overflow-hidden rounded-full bg-white/10 text-[11px] font-semibold">
      {Object.entries(LANGS).map(([code, label]) => (
        <button
          key={code}
          onClick={() => setLang(code)}
          className={`px-2 py-1 ${lang === code ? 'bg-line text-black' : 'text-neutral-300'}`}
        >
          {label}
        </button>
      ))}
    </div>
  )
}
